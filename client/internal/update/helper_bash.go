package update

import (
	"fmt"
	"strings"
)

// unixHelper renders the Bash helper. Every value is embedded with explicit
// quoting; the script never opens a terminal and appends its output to the
// update log.
func unixHelper(data helperData) string {
	var out strings.Builder
	out.WriteString("#!/bin/bash\n")
	out.WriteString("# Generated by kitsune-whisper. Installs one staged update without a terminal.\n")
	fmt.Fprintf(&out, "STAGE=%s\n", shellQuote(data.Stage))
	fmt.Fprintf(&out, "INSTALLER=%s\n", shellQuote(data.Installer))
	fmt.Fprintf(&out, "TAG=%s\n", shellQuote(data.Tag))
	fmt.Fprintf(&out, "LOG=%s\n", shellQuote(data.LogPath))
	fmt.Fprintf(&out, "RESULT=%s\n", shellQuote(data.ResultPath))
	fmt.Fprintf(&out, "CLIENT=%s\n", shellQuote(data.ClientPath))
	fmt.Fprintf(&out, "CONFIG=%s\n", shellQuote(data.ConfigPath))
	fmt.Fprintf(&out, "CLIENT_PID=%d\n", data.ClientPID)
	fmt.Fprintf(&out, "TIMEOUT=%d\n", data.TimeoutSeconds)
	if data.ClientOnly {
		out.WriteString("CLIENT_ONLY=1\n")
	} else {
		out.WriteString("CLIENT_ONLY=0\n")
	}
	if data.ServerSelected {
		out.WriteString("SERVER_SELECTED=1\n")
	} else {
		out.WriteString("SERVER_SELECTED=0\n")
	}
	if data.ServerWasRunning {
		out.WriteString("SERVER_WAS_RUNNING=1\n")
	} else {
		out.WriteString("SERVER_WAS_RUNNING=0\n")
	}
	fmt.Fprintf(&out, "TAG_JSON=%s\n", shellQuote(jsonLiteral(data.Tag)))
	fmt.Fprintf(&out, "LOG_JSON=%s\n", shellQuote(jsonLiteral(data.LogPath)))

	out.WriteString(`
mkdir -p "$(dirname "$LOG")" 2>/dev/null || true
exec >>"$LOG" 2>&1
echo "== kitsune-whisper update $TAG started $(date -u +%Y-%m-%dT%H:%M:%SZ) =="

# The installer on Windows force-stops kitsune-client. On both platforms the
# helper waits for the old Client to exit and release the single-instance lock.
wait_deadline=$(( $(date +%s) + 300 ))
while kill -0 "$CLIENT_PID" 2>/dev/null; do
  if [ "$(date +%s)" -ge "$wait_deadline" ]; then
    echo "the Client did not exit within 5 minutes"
    break
  fi
  sleep 0.2
done

timed_out=false
mkdir -p "$(dirname "$RESULT")" 2>/dev/null || true

args=(--from "$STAGE" --version "$TAG")
if [ "$CLIENT_ONLY" = "1" ]; then
  args+=(--client-only)
fi
bash "$INSTALLER" "${args[@]}" &
installer_pid=$!
timeout_deadline=$(( $(date +%s) + TIMEOUT ))
while kill -0 "$installer_pid" 2>/dev/null; do
  if [ "$(date +%s)" -ge "$timeout_deadline" ]; then
    echo "the installer timed out after $TIMEOUT seconds"
    kill -TERM "$installer_pid" 2>/dev/null || true
    sleep 1
    kill -KILL "$installer_pid" 2>/dev/null || true
    timed_out=true
    break
  fi
  sleep 0.2
done
wait "$installer_pid"
installer_exit=$?
if [ "$timed_out" = "true" ]; then
  installer_exit=124
fi

client_updated=false
reported="$("$CLIENT" --version 2>/dev/null | head -n 1 | awk '{print $NF}')"
reported="${reported#v}"
reported="${reported#V}"
wanted="${TAG#v}"
wanted="${wanted#V}"
if [ -n "$reported" ] && [ "$reported" = "$wanted" ]; then
  client_updated=true
fi

server_updated=false
if [ "$SERVER_SELECTED" = "1" ] && [ "$timed_out" = "false" ] && [ "$installer_exit" -eq 0 ]; then
  server_updated=true
fi

if [ "$timed_out" = "true" ]; then
  status=timeout
elif [ "$installer_exit" -eq 0 ]; then
  status=success
elif [ "$client_updated" = "true" ] && [ "$SERVER_SELECTED" = "1" ]; then
  status=partial
else
  status=error
fi

server_was_running=false
if [ "$SERVER_WAS_RUNNING" = "1" ]; then server_was_running=true; fi

write_result() {
  tmp="${RESULT}.tmp.$$"
  cat >"$tmp" <<EOF
{
  "status": "$status",
  "tag": $TAG_JSON,
  "client_updated": $client_updated,
  "server_updated": $server_updated,
  "server_was_running": $server_was_running,
  "timed_out": $timed_out,
  "installer_exit": $installer_exit,
  "finished_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "log_path": $LOG_JSON
}
EOF
  chmod 600 "$tmp"
  mv -f "$tmp" "$RESULT"
}
write_result

# Always bring the Client back, even when the installer failed or timed out.
# The newly installed binary is launched, never the old image with restart.Exec.
if [ -n "$CONFIG" ]; then
  nohup "$CLIENT" --config "$CONFIG" gui >>"$LOG" 2>&1 &
else
  nohup "$CLIENT" gui >>"$LOG" 2>&1 &
fi
echo "== kitsune-whisper update $TAG finished with $status =="
`)
	return out.String()
}
