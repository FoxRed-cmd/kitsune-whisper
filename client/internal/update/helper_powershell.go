package update

import (
	"fmt"
	"strings"
)

// windowsHelper renders the PowerShell helper. It runs install.ps1 through
// pwsh with no console window and relaunches the installed Client with gui.
func windowsHelper(data helperData) string {
	var out strings.Builder
	out.WriteString("# Generated by kitsune-whisper. Installs one staged update without a terminal.\n")
	out.WriteString("$ErrorActionPreference = 'Continue'\n")
	fmt.Fprintf(&out, "$Stage = %s\n", powershellQuote(data.Stage))
	fmt.Fprintf(&out, "$Installer = %s\n", powershellQuote(data.Installer))
	fmt.Fprintf(&out, "$Tag = %s\n", powershellQuote(data.Tag))
	fmt.Fprintf(&out, "$LogPath = %s\n", powershellQuote(data.LogPath))
	fmt.Fprintf(&out, "$ResultPath = %s\n", powershellQuote(data.ResultPath))
	fmt.Fprintf(&out, "$ClientPath = %s\n", powershellQuote(data.ClientPath))
	fmt.Fprintf(&out, "$ConfigPath = %s\n", powershellQuote(data.ConfigPath))
	fmt.Fprintf(&out, "$ClientPid = %d\n", data.ClientPID)
	fmt.Fprintf(&out, "$TimeoutSeconds = %d\n", data.TimeoutSeconds)
	fmt.Fprintf(&out, "$ClientExitWaitSeconds = %d\n", data.ClientExitWaitSeconds)
	if data.ClientOnly {
		out.WriteString("$ClientOnly = $true\n")
	} else {
		out.WriteString("$ClientOnly = $false\n")
	}
	if data.ServerSelected {
		out.WriteString("$ServerSelected = $true\n")
	} else {
		out.WriteString("$ServerSelected = $false\n")
	}
	if data.ServerWasRunning {
		out.WriteString("$ServerWasRunning = $true\n")
	} else {
		out.WriteString("$ServerWasRunning = $false\n")
	}

	out.WriteString(`
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $LogPath) | Out-Null
"[kitsune-whisper] update $Tag started $((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))" |
  Out-File -FilePath $LogPath -Append -Encoding utf8

# The Windows installer force-stops kitsune-client, so the helper waits for the
# old Client to exit before the installer replaces its files. The wait is fixed
# by the Client so a stuck process cannot block the update forever.
$waitDeadline = (Get-Date).AddSeconds($ClientExitWaitSeconds)
while (Get-Process -Id $ClientPid -ErrorAction SilentlyContinue) {
  if ((Get-Date) -gt $waitDeadline) {
    "the Client did not exit within $ClientExitWaitSeconds seconds" | Out-File -FilePath $LogPath -Append -Encoding utf8
    break
  }
  Start-Sleep -Milliseconds 200
}

$TimedOut = $false
$arguments = @(
  "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass",
  "-File", $Installer, "-From", $Stage, "-Version", $Tag
)
if ($ClientOnly) {
  $arguments += "-ClientOnly"
}
$installerInfo = [System.Diagnostics.ProcessStartInfo]::new()
$installerInfo.FileName = "pwsh.exe"
foreach ($argument in $arguments) { $installerInfo.ArgumentList.Add($argument) }
$installerInfo.UseShellExecute = $false
$installerProcess = [System.Diagnostics.Process]::Start($installerInfo)
if (-not $installerProcess.WaitForExit($TimeoutSeconds * 1000)) {
  $TimedOut = $true
  try { $installerProcess.Kill($true) } catch {}
  $InstallerExit = 124
  "the installer timed out after $TimeoutSeconds seconds" | Out-File -FilePath $LogPath -Append -Encoding utf8
} else {
  $InstallerExit = $installerProcess.ExitCode
}

$ClientUpdated = $false
$reported = (& $ClientPath --version 2>$null | Select-Object -First 1)
if ($reported) {
  $reported = (($reported -split '\s+')[-1]).TrimStart('v', 'V')
  $wanted = $Tag.TrimStart('v', 'V')
  if ($reported -eq $wanted) { $ClientUpdated = $true }
}

$ServerUpdated = $false
if ($ServerSelected -and (-not $TimedOut) -and ($InstallerExit -eq 0)) {
  $ServerUpdated = $true
}

if ($TimedOut) {
  $Status = "timeout"
} elseif ($InstallerExit -eq 0) {
  $Status = "success"
} elseif ($ClientUpdated -and $ServerSelected) {
  $Status = "partial"
} else {
  $Status = "error"
}

$result = [ordered]@{
  status = $Status
  tag = $Tag
  client_updated = $ClientUpdated
  server_updated = $ServerUpdated
  server_was_running = $ServerWasRunning
  timed_out = $TimedOut
  installer_exit = $InstallerExit
  finished_at = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
  log_path = $LogPath
}
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $ResultPath) | Out-Null
$resultTemp = "$ResultPath.tmp.$PID"
$result | ConvertTo-Json | Set-Content -Path $resultTemp -Encoding utf8
Move-Item -Force $resultTemp $ResultPath

# Always bring the Client back, even after a failed or timed-out installer.
$clientArguments = [System.Collections.Generic.List[string]]::new()
if ($ConfigPath -ne "") {
  $clientArguments.Add("--config")
  $clientArguments.Add($ConfigPath)
}
$clientArguments.Add("gui")
$clientInfo = [System.Diagnostics.ProcessStartInfo]::new()
$clientInfo.FileName = $ClientPath
foreach ($argument in $clientArguments) { $clientInfo.ArgumentList.Add($argument) }
$clientInfo.UseShellExecute = $false
[System.Diagnostics.Process]::Start($clientInfo) | Out-Null
"[kitsune-whisper] update $Tag finished with $Status" | Out-File -FilePath $LogPath -Append -Encoding utf8
`)
	return out.String()
}
